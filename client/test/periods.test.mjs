import assert from 'node:assert/strict';
import { reportPeriod, currentMonth, dueSoon, cutoff } from '../src/periods.js';
import { fuelSummary, buildReport } from '../src/calc.js';
assert.deepEqual(reportPeriod('2026-10', 'fuel'), { from: '2026-09-08', to: '2026-10-07' });
assert.deepEqual(reportPeriod('2026-10', 'mileage'), { from: '2026-09-10', to: '2026-10-09' });
assert.equal(currentMonth('2026-10-07', 'fuel'), '2026-10');
assert.equal(currentMonth('2026-10-08', 'fuel'), '2026-11');
const settings = { 'fuel:2026-10': 5, 'fuel:2026-11': 12 };
assert.deepEqual(reportPeriod('2026-11', 'fuel', settings), { from: '2026-10-06', to: '2026-11-12' });
assert.deepEqual(reportPeriod('2027-01', 'mileage'), { from: '2026-12-10', to: '2027-01-09' });
assert.equal(cutoff('2028-02', 'fuel', { 'fuel:2028-02': 31 }), '2028-02-29');
assert.equal(dueSoon('2026-10-04', 'fuel'), '2026-10-07');
assert.equal(dueSoon('2026-10-03', 'fuel'), null);
assert.equal(dueSoon('2026-10-08', 'fuel'), null);
const fuel = [{purchaseDate:'2026-10-07', amountPence:100}, {purchaseDate:'2026-10-08', amountPence:200}];
assert.equal(fuelSummary({fuel, ...reportPeriod('2026-10','fuel')}).totalPence,100);
assert.equal(fuelSummary({fuel, ...reportPeriod('2026-11','fuel')}).totalPence,200);
const trips = [{tripDate:'2026-10-09',miles:10}, {tripDate:'2026-10-10',miles:20}];
assert.equal(buildReport({trips,rates:[], ...reportPeriod('2026-10','mileage')}).totalMiles,10);
assert.equal(buildReport({trips,rates:[], ...reportPeriod('2026-11','mileage')}).totalMiles,20);
console.log('Monthly cutoff tests passed');
